/// Platform-enforced limits that cannot be overridden by users
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlatformLimits {
    /// Maximum position size as percentage of account (platform cap)
    pub max_position_pct_cap: f64,
    /// Maximum daily loss as percentage of account
    pub max_daily_loss_pct_cap: f64,
    /// Minimum required backtest period (days)
    pub min_backtest_days: u32,
    /// Maximum leverage allowed
    pub max_leverage: f64,
    /// Capital threshold requiring admin review (USD)
    pub admin_review_threshold_usd: f64,
    /// Capital threshold requiring multi-sig approval (USD)
    pub multi_sig_threshold_usd: f64,
}

impl Default for PlatformLimits {
    fn default() -> Self {
        Self {
            max_position_pct_cap: 0.20,           // Max 20% of account in one position
            max_daily_loss_pct_cap: 0.10,         // Max 10% daily loss
            min_backtest_days: 30,                // At least 30 days of data
            max_leverage: 3.0,                    // Max 3x leverage
            admin_review_threshold_usd: 25_000.0, // Admin review for >$25K
            multi_sig_threshold_usd: 100_000.0,   // Multi-sig for >$100K
        }
    }
}

/// Result of platform validation
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlatformValidation {
    /// Whether the deployment passes platform hard limits
    pub passes_hard_limits: bool,
    /// List of hard limit violations (if any)
    pub violations: Vec<HardLimitViolation>,
    /// Adjusted values (platform may cap user values)
    pub adjusted_config: Option<UserRiskConfig>,
    /// Required approval level based on capital
    pub required_approval: ApprovalRequirement,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HardLimitViolation {
    pub limit_name: String,
    pub user_value: f64,
    pub platform_limit: f64,
    pub message: String,
    /// Whether this can be auto-adjusted or requires rejection
    pub auto_adjustable: bool,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum ApprovalRequirement {
    /// No admin approval needed
    None,
    /// Single admin must approve
    AdminReview,
    /// Multiple admins must approve
    MultiSigRequired,
}

/// Validate deployment request against platform hard limits
pub fn validate_platform_limits(
    user_config: &UserRiskConfig,
    metrics: &BacktestMetrics,
    limits: &PlatformLimits,
) -> PlatformValidation {
    let mut violations = Vec::new();
    let mut adjusted_config = user_config.clone();
    let mut needs_adjustment = false;
    
    // Check position size cap
    if user_config.max_position_pct > limits.max_position_pct_cap {
        violations.push(HardLimitViolation {
            limit_name: "max_position_pct".to_string(),
            user_value: user_config.max_position_pct,
            platform_limit: limits.max_position_pct_cap,
            message: format!(
                "Position size {:.1}% exceeds platform cap of {:.1}% - will be reduced",
                user_config.max_position_pct * 100.0,
                limits.max_position_pct_cap * 100.0
            ),
            auto_adjustable: true,
        });
        adjusted_config.max_position_pct = limits.max_position_pct_cap;
        needs_adjustment = true;
    }
    
    // Check daily loss as percentage of allocated capital
    let daily_loss_pct = user_config.daily_loss_limit_usd / user_config.allocated_capital_usd;
    if daily_loss_pct > limits.max_daily_loss_pct_cap {
        let max_daily_loss = user_config.allocated_capital_usd * limits.max_daily_loss_pct_cap;
        violations.push(HardLimitViolation {
            limit_name: "daily_loss_limit".to_string(),
            user_value: user_config.daily_loss_limit_usd,
            platform_limit: max_daily_loss,
            message: format!(
                "Daily loss limit ${:.2} exceeds {:.1}% of capital - will be reduced to ${:.2}",
                user_config.daily_loss_limit_usd,
                limits.max_daily_loss_pct_cap * 100.0,
                max_daily_loss
            ),
            auto_adjustable: true,
        });
        adjusted_config.daily_loss_limit_usd = max_daily_loss;
        needs_adjustment = true;
    }
    
    // Check leverage cap
    if user_config.leverage > limits.max_leverage {
        violations.push(HardLimitViolation {
            limit_name: "leverage".to_string(),
            user_value: user_config.leverage,
            platform_limit: limits.max_leverage,
            message: format!(
                "Leverage {:.1}x exceeds platform cap of {:.1}x - will be reduced",
                user_config.leverage, limits.max_leverage
            ),
            auto_adjustable: true,
        });
        adjusted_config.leverage = limits.max_leverage;
        needs_adjustment = true;
    }

    // Check minimum backtest period (non-adjustable - must reject)
    if metrics.total_days < limits.min_backtest_days {
        violations.push(HardLimitViolation {
            limit_name: "min_backtest_days".to_string(),
            user_value: metrics.total_days as f64,
            platform_limit: limits.min_backtest_days as f64,
            message: format!(
                "Backtest period of {} days is below minimum required {} days",
                metrics.total_days,
                limits.min_backtest_days
            ),
            auto_adjustable: false,
        });
    }
    
    // Determine if passes (only fails if non-adjustable violations exist)
    let passes = violations.iter().all(|v| v.auto_adjustable);
    
    // Determine approval requirement based on capital
    let required_approval = if user_config.allocated_capital_usd >= limits.multi_sig_threshold_usd {
        ApprovalRequirement::MultiSigRequired
    } else if user_config.allocated_capital_usd >= limits.admin_review_threshold_usd {
        ApprovalRequirement::AdminReview
    } else {
        ApprovalRequirement::None
    };
    
    PlatformValidation {
        passes_hard_limits: passes,
        violations,
        adjusted_config: if needs_adjustment { Some(adjusted_config) } else { None },
        required_approval,
    }
}

