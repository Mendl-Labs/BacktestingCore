/// Advisory warning shown to user - informational only, does not block deployment
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AdvisoryWarning {
    /// Warning severity (for UI coloring)
    pub severity: WarningSeverity,
    /// Warning category
    pub category: WarningCategory,
    /// Human-readable warning message
    pub message: String,
    /// The metric that triggered this warning
    pub metric_name: String,
    /// Actual value of the metric
    pub actual_value: f64,
    /// Typical/reference value (for comparison)
    pub reference_value: f64,
    /// Additional context or suggestions
    pub context: Option<String>,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Hash)]
pub enum WarningSeverity {
    /// Informational - just FYI
    Info,
    /// Caution - worth considering
    Caution,
    /// Warning - significant concern
    Warning,
    /// Critical - high risk indicator
    Critical,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum WarningCategory {
    Performance,
    Risk,
    StatisticalSignificance,
    MarketConditions,
    ParameterStability,
}

/// Generate advisory warnings based on backtest metrics
/// These are INFORMATIONAL ONLY - they do NOT block deployment
pub fn generate_advisory_warnings(metrics: &BacktestMetrics) -> Vec<AdvisoryWarning> {
    let mut warnings = Vec::new();
    
    // Sharpe ratio advisory
    if metrics.sharpe_ratio < 0.5 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Warning,
            category: WarningCategory::Performance,
            message: "Sharpe ratio is below 0.5, indicating poor risk-adjusted returns".to_string(),
            metric_name: "sharpe_ratio".to_string(),
            actual_value: metrics.sharpe_ratio,
            reference_value: 1.0,
            context: Some("Sharpe > 1.0 is typically considered acceptable, > 2.0 is good".to_string()),
        });
    } else if metrics.sharpe_ratio < 1.0 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Caution,
            category: WarningCategory::Performance,
            message: "Sharpe ratio is below 1.0".to_string(),
            metric_name: "sharpe_ratio".to_string(),
            actual_value: metrics.sharpe_ratio,
            reference_value: 1.0,
            context: Some("Many institutional traders require Sharpe > 1.0".to_string()),
        });
    }
    
    // Drawdown advisory
    if metrics.max_drawdown_pct > 0.30 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Critical,
            category: WarningCategory::Risk,
            message: format!("Maximum drawdown of {:.1}% is very high", metrics.max_drawdown_pct * 100.0),
            metric_name: "max_drawdown_pct".to_string(),
            actual_value: metrics.max_drawdown_pct,
            reference_value: 0.15,
            context: Some("You could lose more than 30% of your position at some point".to_string()),
        });
    } else if metrics.max_drawdown_pct > 0.20 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Warning,
            category: WarningCategory::Risk,
            message: format!("Maximum drawdown of {:.1}% is elevated", metrics.max_drawdown_pct * 100.0),
            metric_name: "max_drawdown_pct".to_string(),
            actual_value: metrics.max_drawdown_pct,
            reference_value: 0.15,
            context: Some("Consider if you can tolerate this level of drawdown".to_string()),
        });
    }
    
    // Statistical significance advisory
    if metrics.total_trades < 30 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Critical,
            category: WarningCategory::StatisticalSignificance,
            message: format!("Only {} trades in backtest - results may not be statistically significant", metrics.total_trades),
            metric_name: "total_trades".to_string(),
            actual_value: metrics.total_trades as f64,
            reference_value: 100.0,
            context: Some("Recommend at least 100 trades for statistical confidence".to_string()),
        });
    } else if metrics.total_trades < 100 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Caution,
            category: WarningCategory::StatisticalSignificance,
            message: format!("{} trades may have limited statistical significance", metrics.total_trades),
            metric_name: "total_trades".to_string(),
            actual_value: metrics.total_trades as f64,
            reference_value: 100.0,
            context: None,
        });
    }
    
    // Win rate advisory (informational - some strategies win small and lose big, others opposite)
    if metrics.win_rate < 0.40 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Info,
            category: WarningCategory::Performance,
            message: format!("Win rate of {:.1}% is below 50%", metrics.win_rate * 100.0),
            metric_name: "win_rate".to_string(),
            actual_value: metrics.win_rate,
            reference_value: 0.50,
            context: Some("This can be fine if average wins are larger than average losses (check profit factor)".to_string()),
        });
    }
    
    // Parameter stability advisory
    if metrics.parameter_stability_score < 0.6 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Warning,
            category: WarningCategory::ParameterStability,
            message: "Parameters showed instability across walk-forward windows".to_string(),
            metric_name: "parameter_stability_score".to_string(),
            actual_value: metrics.parameter_stability_score,
            reference_value: 0.8,
            context: Some("Strategy may be overfit to specific market conditions".to_string()),
        });
    }
    
    // Out-of-sample vs in-sample comparison
    if metrics.out_of_sample_sharpe < metrics.sharpe_ratio * 0.5 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Warning,
            category: WarningCategory::ParameterStability,
            message: "Out-of-sample performance significantly lower than in-sample".to_string(),
            metric_name: "out_of_sample_sharpe".to_string(),
            actual_value: metrics.out_of_sample_sharpe,
            reference_value: metrics.sharpe_ratio,
            context: Some("This may indicate overfitting to historical data".to_string()),
        });
    }
    
    // Monte Carlo probability warning
    if metrics.monte_carlo_probability_of_profit < 0.6 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Warning,
            category: WarningCategory::Risk,
            message: format!("Monte Carlo shows {:.1}% probability of profit", metrics.monte_carlo_probability_of_profit * 100.0),
            metric_name: "monte_carlo_probability_of_profit".to_string(),
            actual_value: metrics.monte_carlo_probability_of_profit,
            reference_value: 0.70,
            context: Some("Across randomized scenarios, profitability is uncertain".to_string()),
        });
    }
    
    // Backtest period advisory
    if metrics.total_days < 180 {
        warnings.push(AdvisoryWarning {
            severity: WarningSeverity::Caution,
            category: WarningCategory::StatisticalSignificance,
            message: format!("Backtest period of {} days is relatively short", metrics.total_days),
            metric_name: "total_days".to_string(),
            actual_value: metrics.total_days as f64,
            reference_value: 365.0,
            context: Some("Longer backtests capture more market conditions".to_string()),
        });
    }
    
    warnings
}

