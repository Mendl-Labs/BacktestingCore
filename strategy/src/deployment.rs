/// Risk acknowledgment that user must explicitly accept
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RiskAcknowledgment {
    /// Type of risk being acknowledged
    pub risk_type: RiskType,
    /// The specific statement user is acknowledging
    pub statement: String,
    /// Whether user has acknowledged this risk
    pub acknowledged: bool,
    /// Timestamp when acknowledged
    pub acknowledged_at: Option<DateTime<Utc>>,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum RiskType {
    /// General trading risk
    TradingRisk,
    /// Specific drawdown risk
    DrawdownRisk,
    /// Capital loss risk
    CapitalLossRisk,
    /// Past performance disclaimer
    PastPerformance,
    /// Strategy-specific risk
    StrategySpecific,
}

/// Generate required risk acknowledgments based on metrics and config
pub fn generate_required_acknowledgments(
    metrics: &BacktestMetrics,
    user_config: &UserRiskConfig,
) -> Vec<RiskAcknowledgment> {
    let mut acks = Vec::new();
    
    // Always required: General trading risk
    acks.push(RiskAcknowledgment {
        risk_type: RiskType::TradingRisk,
        statement: "I understand that algorithmic trading involves significant risk and I may lose money.".to_string(),
        acknowledged: false,
        acknowledged_at: None,
    });
    
    // Always required: Past performance disclaimer
    acks.push(RiskAcknowledgment {
        risk_type: RiskType::PastPerformance,
        statement: "I understand that past backtest performance does not guarantee future results.".to_string(),
        acknowledged: false,
        acknowledged_at: None,
    });
    
    // Specific drawdown acknowledgment if high
    if metrics.max_drawdown_pct > 0.15 {
        acks.push(RiskAcknowledgment {
            risk_type: RiskType::DrawdownRisk,
            statement: format!(
                "I understand this strategy showed a maximum drawdown of {:.1}% in backtesting, and I may experience similar or larger drawdowns in live trading.",
                metrics.max_drawdown_pct * 100.0
            ),
            acknowledged: false,
            acknowledged_at: None,
        });
    }
    
    // Capital loss acknowledgment for significant allocations
    if user_config.allocated_capital_usd > 5000.0 {
        acks.push(RiskAcknowledgment {
            risk_type: RiskType::CapitalLossRisk,
            statement: format!(
                "I am allocating ${:.2} to this strategy and I can afford to lose this amount.",
                user_config.allocated_capital_usd
            ),
            acknowledged: false,
            acknowledged_at: None,
        });
    }
    
    // Strategy-specific risks
    if metrics.win_rate < 0.40 && metrics.profit_factor > 1.5 {
        acks.push(RiskAcknowledgment {
            risk_type: RiskType::StrategySpecific,
            statement: "I understand this strategy has a low win rate and relies on large winning trades to be profitable. I may experience many consecutive losses.".to_string(),
            acknowledged: false,
            acknowledged_at: None,
        });
    }
    
    if metrics.parameter_stability_score < 0.7 {
        acks.push(RiskAcknowledgment {
            risk_type: RiskType::StrategySpecific,
            statement: "I understand this strategy showed parameter instability in walk-forward testing, which may indicate sensitivity to market conditions.".to_string(),
            acknowledged: false,
            acknowledged_at: None,
        });
    }
    
    acks
}

