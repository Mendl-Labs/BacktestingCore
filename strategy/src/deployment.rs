// DEPLOYMENT REQUEST BUILDER
// ============================================================================

impl DeploymentRequest {
    /// Create a new deployment request from backtest results
    pub fn new(
        user_id: Uuid,
        strategy_id: String,
        strategy_name: String,
        symbol: String,
        exchange: String,
        metrics: BacktestMetrics,
        user_config: UserRiskConfig,
    ) -> Self {
        let advisory_warnings = generate_advisory_warnings(&metrics);
        let risk_acknowledgments = generate_required_acknowledgments(&metrics, &user_config);
        let platform_validation = validate_platform_limits(
            &user_config,
            &metrics,
            &PlatformLimits::default(),
        );
        
        let initial_status = if !platform_validation.passes_hard_limits {
            DeploymentStatus::RejectedByPlatform
        } else {
            DeploymentStatus::PendingUserReview
        };
        
        let now = Utc::now();
        
        Self {
            request_id: Uuid::new_v4(),
            user_id,
            strategy_id,
            strategy_name,
            symbol,
            exchange,
            backtest_metrics: metrics,
            user_risk_config: user_config,
            advisory_warnings,
            risk_acknowledgments,
            status: initial_status,
            platform_validation,
            created_at: now,
            updated_at: now,
        }
    }
    
    /// Check if user has acknowledged all required risks
    pub fn all_risks_acknowledged(&self) -> bool {
        self.risk_acknowledgments.iter().all(|ack| ack.acknowledged)
    }
    
    /// Acknowledge a specific risk
    pub fn acknowledge_risk(&mut self, risk_type: RiskType) -> bool {
        if let Some(ack) = self.risk_acknowledgments.iter_mut().find(|a| a.risk_type == risk_type) {
            ack.acknowledged = true;
            ack.acknowledged_at = Some(Utc::now());
            self.updated_at = Utc::now();
            
            // Update status if all acknowledged
            if self.status == DeploymentStatus::PendingRiskAcknowledgment && self.all_risks_acknowledged() {
                self.status = match self.platform_validation.required_approval {
                    ApprovalRequirement::None => DeploymentStatus::Approved,
                    ApprovalRequirement::AdminReview => DeploymentStatus::PendingAdminApproval,
                    ApprovalRequirement::MultiSigRequired => DeploymentStatus::PendingMultiSigApproval,
                };
            }
            true
        } else {
            false
        }
    }
    
    /// User confirms they want to proceed (moves to risk acknowledgment)
    pub fn user_confirms_review(&mut self) {
        if self.status == DeploymentStatus::PendingUserReview {
            self.status = DeploymentStatus::PendingRiskAcknowledgment;
            self.updated_at = Utc::now();
        }
    }
    
    /// User cancels deployment
    pub fn cancel(&mut self) {
        self.status = DeploymentStatus::CancelledByUser;
        self.updated_at = Utc::now();
    }
    
    /// Admin approves deployment
    pub fn admin_approve(&mut self, _admin_id: Uuid, _admin_name: String, _notes: Option<String>) {
        if self.status == DeploymentStatus::PendingAdminApproval {
            self.status = DeploymentStatus::Approved;
            self.updated_at = Utc::now();
            // In production, store AdminApproval record
        }
    }
    
    /// Admin rejects deployment
    pub fn admin_reject(&mut self, _admin_id: Uuid, _admin_name: String, _reason: String) {
        if self.status == DeploymentStatus::PendingAdminApproval 
            || self.status == DeploymentStatus::PendingMultiSigApproval {
            self.status = DeploymentStatus::RejectedByAdmin;
            self.updated_at = Utc::now();
            // In production, store AdminApproval record with rejection reason
        }
    }
    
    /// Check if deployment is ready to go live
    pub fn is_ready_for_deployment(&self) -> bool {
        self.status == DeploymentStatus::Approved
    }
    
    /// Get count of warnings by severity
    pub fn warning_counts(&self) -> HashMap<WarningSeverity, usize> {
        let mut counts = HashMap::new();
        for warning in &self.advisory_warnings {
            *counts.entry(warning.severity).or_insert(0) += 1;
        }
        counts
    }
}

