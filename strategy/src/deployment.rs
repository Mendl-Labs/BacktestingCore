/// Risk configuration chosen by the user
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UserRiskConfig {
    /// Maximum position size as percentage of account
    pub max_position_pct: f64,
    /// User's daily loss limit (absolute value in USD)
    pub daily_loss_limit_usd: f64,
    /// User's per-trade stop loss percentage
    pub stop_loss_pct: f64,
    /// Optional take profit percentage
    pub take_profit_pct: Option<f64>,
    /// Capital allocated to this strategy (USD)
    pub allocated_capital_usd: f64,
    /// Leverage multiplier requested for this deployment. `1.0` = no leverage.
    #[serde(default = "default_user_leverage")]
    pub leverage: f64,
}

fn default_user_leverage() -> f64 { 1.0 }

impl Default for UserRiskConfig {
    fn default() -> Self {
        Self {
            max_position_pct: 0.05,      // 5% default
            daily_loss_limit_usd: 500.0, // $500 default
            stop_loss_pct: 0.02,         // 2% default
            take_profit_pct: None,
            allocated_capital_usd: 10000.0, // $10K default
            leverage: default_user_leverage(),
        }
    }
}

