// DEPLOYMENT STATUS & WORKFLOW
// ============================================================================

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum DeploymentStatus {
    /// User is reviewing backtest results
    PendingUserReview,
    /// Waiting for user to acknowledge risks
    PendingRiskAcknowledgment,
    /// Waiting for admin approval (high capital)
    PendingAdminApproval,
    /// Waiting for multi-sig approval (very high capital)
    PendingMultiSigApproval,
    /// Approved and ready to deploy
    Approved,
    /// Rejected by platform (hard limit violation)
    RejectedByPlatform,
    /// Rejected by admin
    RejectedByAdmin,
    /// Cancelled by user
    CancelledByUser,
    /// Successfully deployed to SignalEngine
    Deployed,
    /// Deployment failed (technical error)
    DeploymentFailed,
}

/// Admin approval record
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AdminApproval {
    pub admin_id: Uuid,
    pub admin_name: String,
    pub decision: AdminDecision,
    pub notes: Option<String>,
    pub decided_at: DateTime<Utc>,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum AdminDecision {
    Approved,
    Rejected,
    RequestMoreInfo,
}

