/// A deployment request initiated by the user after reviewing backtest results
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DeploymentRequest {
    /// Unique identifier for this deployment request
    pub request_id: Uuid,
    /// User who initiated the deployment
    pub user_id: Uuid,
    /// Strategy identifier
    pub strategy_id: String,
    /// Strategy name
    pub strategy_name: String,
    /// Trading pair
    pub symbol: String,
    /// Exchange to deploy on
    pub exchange: String,
    /// Backtest performance metrics (ALL of them, unfiltered)
    pub backtest_metrics: BacktestMetrics,
    /// User's chosen risk configuration
    pub user_risk_config: UserRiskConfig,
    /// Advisory warnings generated by platform (informational only)
    pub advisory_warnings: Vec<AdvisoryWarning>,
    /// Risk acknowledgments signed by user
    pub risk_acknowledgments: Vec<RiskAcknowledgment>,
    /// Current status of the deployment
    pub status: DeploymentStatus,
    /// Platform's hard limit validation result
    pub platform_validation: PlatformValidation,
    /// Timestamps
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

/// All backtest metrics - shown to user without filtering
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BacktestMetrics {
    // Core performance
    pub sharpe_ratio: f64,
    pub sortino_ratio: f64,
    pub calmar_ratio: f64,
    pub profit_factor: f64,
    pub win_rate: f64,
    pub total_return_pct: f64,
    pub annualized_return_pct: f64,
    
    // Risk metrics
    pub max_drawdown_pct: f64,
    pub avg_drawdown_pct: f64,
    pub max_drawdown_duration_days: u32,
    pub volatility_annualized: f64,
    pub var_95: f64,  // Value at Risk 95%
    pub cvar_95: f64, // Conditional VaR 95%
    
    // Trade statistics
    pub total_trades: u64,
    pub avg_trade_return_pct: f64,
    pub avg_winning_trade_pct: f64,
    pub avg_losing_trade_pct: f64,
    pub largest_win_pct: f64,
    pub largest_loss_pct: f64,
    pub avg_trade_duration_hours: f64,
    
    // Walk-forward specific
    pub out_of_sample_sharpe: f64,
    pub parameter_stability_score: f64,
    pub profitable_windows: u32,
    pub total_windows: u32,
    
    // Monte Carlo results
    pub monte_carlo_median_return: f64,
    pub monte_carlo_5th_percentile: f64,
    pub monte_carlo_95th_percentile: f64,
    pub monte_carlo_probability_of_profit: f64,
    
    // Backtest period
    pub backtest_start: DateTime<Utc>,
    pub backtest_end: DateTime<Utc>,
    pub total_days: u32,
}

