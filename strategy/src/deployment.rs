//! User-Controlled Deployment Workflow
//!
//! This module implements a user-centric deployment flow where:
//! - Users see ALL backtest results (no gatekeeping)
//! - Users decide whether to deploy (their money, their choice)
//! - Platform provides advisory warnings (informational, not blocking)
//! - Platform enforces hard safety limits (non-negotiable)
//! - High-capital deployments require admin review
//!
//! ## Philosophy
//!
//! The platform's role is to:
//! 1. Provide accurate metrics and analysis
//! 2. Warn users of potential risks (advisory)
//! 3. Enforce account-level safety rails (hard limits)
//! 4. Maintain audit trail for compliance
//!
//! The platform does NOT:
//! - Decide what Sharpe ratio is "good enough"
//! - Block strategies based on arbitrary thresholds
//! - Override user decisions about their own capital

