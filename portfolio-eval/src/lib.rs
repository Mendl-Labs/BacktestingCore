//! `portfolio-eval`: pure, deterministic portfolio-level evaluation statistics (stage PF5 of
//! `product-mandate/PORTFOLIO_FIRST_BACKTESTER_DESIGN.md`, layer D).
//!
//! It answers questions about SERIES OF PORTFOLIO RETURNS. It never simulates trading, reads data, touches the clock,
//! the network, a database or the operating system's randomness; the Engine glue (PF6) feeds it the net return series
//! of book simulations.
//!
//! | module | what | design |
//! |---|---|---|
//! | [`folds`] | walk-forward, purged K-fold and CPCV index ranges with purge and embargo | 4.3 |
//! | [`bootstrap`] | stationary block bootstrap (Politis-Romano), automatic block length (Politis-White) | 4.4 |
//! | [`marginal`] | paired equal-volatility marginal test, minimum detectable effect | 3.4 |
//! | [`hac`] | Newey-West standard errors, spanning-regression alpha | 3.4 |
//! | [`dsr`] | deflated / probabilistic Sharpe, MinTRL, BH q-values, mirrors of Core's formulas | 4.4 |
//! | [`ledger`] | book-level trial ledger, sealed holdout, effective breadth | 4.4 |
//! | [`pbo`] | probability of backtest overfitting (CSCV) | 4.4 |
//! | [`power`] | Monte Carlo of the marginal test's size and power; the committed power table | U7 |
//! | [`detmath`], [`rng`], [`stats`], [`sha256`] | in-crate deterministic primitives | - |
//!
//! # Design choices
//!
//! * **P1 Zero dependencies, no OS randomness.** A seeded xoshiro256** generator lives in [`rng`]; `exp`, `ln`,
//!   `sin`/`cos`, `erfc` and the normal quantile are re-implemented in [`detmath`] from IEEE basic operations so that
//!   the pinned digests and the committed power table are bit-identical on x86_64 and aarch64 (platform `libm` results
//!   differ in the last bit).
//! * **P2 Refuse, never default.** Bad input (NaN, too short, zero variance, singular system, out-of-domain parameter)
//!   returns a typed [`error::EvalError`]; no public function panics, and none returns "0.5 because nothing could be
//!   computed" (the old DSR helper's failure mode).
//! * **P3 The marginal test is a paired Sharpe difference at equal volatility**, bootstrapped over shared rows. It
//!   replaces the retired `marginal_contribution_gate`, whose statistic `(r_i - mean_all)/(n-1)` is zero-sum by
//!   algebra (memory 2026-09-18, placebo suite 2026-09-20). Spanning alpha with HAC errors is reported beside it.
//! * **P4 Power is part of the answer.** [`marginal::MarginalResult::mde`] is always reported and
//!   `POWER_TABLE.md` (generated by `src/bin/power_table.rs`, pinned by `tests/power_table.rs`) says what each sample
//!   length can and cannot detect.
//! * **P5 Trial accounting counts every choice**, dispersion is a robust scale, holdout reuse is flagged post hoc.
//! * **P6 Core's DSR is mirrored, not edited.** [`dsr::core_compat`] reproduces `metrics::significance` and
//!   `metrics::performance` deflated Sharpe formulas so equivalence is tested on shared inputs.
//! * **P7 Overlapping-return trap.** All resampling here is over dates (rows) of already-formed periodic portfolio
//!   returns, with block bootstrap or HAC errors; nothing tests overlapping h-period returns as independent (the
//!   `compute_ic` class of error, memory 2026-09-20).

